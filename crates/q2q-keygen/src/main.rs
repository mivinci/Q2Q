use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD as B64};
use clap::{Parser, Subcommand, ValueEnum};
use ed25519_dalek::pkcs8::{DecodePrivateKey, EncodePrivateKey, EncodePublicKey};
use ed25519_dalek::{Signer, SigningKey};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use std::{
  error::Error,
  fs,
  io::Write,
  path::{Path, PathBuf},
  time::{SystemTime, UNIX_EPOCH},
};

type Result<T> = std::result::Result<T, Box<dyn Error>>;
const MAX_SAFE_INTEGER: u64 = 9_007_199_254_740_991;

#[derive(Parser)]
#[command(version, about)]
struct Args {
  #[command(subcommand)]
  command: Command,
}

#[derive(Subcommand)]
enum Command {
  /// Generate an Ed25519 key pair as JWK/JWKS or PKCS#8/SPKI PEM.
  Keypair {
    #[arg(long)]
    kid: String,
    #[arg(long, value_enum, default_value_t = KeyFormat::Jwk)]
    format: KeyFormat,
    #[arg(long)]
    private_key: PathBuf,
    #[arg(long)]
    public_key: PathBuf,
  },
  /// Sign caller-provided JSON claims. No service-specific claims are inferred.
  Token {
    #[arg(long)]
    key: PathBuf,
    /// JSON object; iat, exp and jti are generated by this tool.
    #[arg(long)]
    claims: PathBuf,
    /// Required for PEM keys; must match the embedded kid for JWK keys.
    #[arg(long)]
    kid: Option<String>,
    #[arg(long, default_value_t = 90)]
    days: u64,
    #[arg(long)]
    output: PathBuf,
  },
}

#[derive(Clone, Copy, ValueEnum, Default)]
enum KeyFormat {
  #[default]
  Jwk,
  Pem,
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Jwk {
  kty: String,
  crv: String,
  alg: String,
  #[serde(rename = "use")]
  usage: String,
  kid: String,
  x: String,
  #[serde(skip_serializing_if = "Option::is_none")]
  d: Option<String>,
}

fn identifier(value: &str) -> Result<()> {
  if value.is_empty()
    || value.len() > 128
    || !value
      .bytes()
      .all(|b| b.is_ascii_alphanumeric() || b"-_.".contains(&b))
  {
    return Err("IDs must contain 1–128 ASCII letters, digits, '-', '_' or '.'".into());
  }
  Ok(())
}

fn random<const N: usize>() -> Result<[u8; N]> {
  let mut bytes = [0; N];
  getrandom::fill(&mut bytes).map_err(|_| "secure random generation failed")?;
  Ok(bytes)
}

// Stage in the destination directory, then publish without replacing existing files.
// tempfile creates files with mode 0600 on Unix, including the final secret files.
fn write_new(path: &Path, bytes: &[u8]) -> Result<()> {
  let parent = path
    .parent()
    .filter(|p| !p.as_os_str().is_empty())
    .unwrap_or(Path::new("."));
  let mut file = tempfile::NamedTempFile::new_in(parent)?;
  file.write_all(bytes)?;
  file.as_file().sync_all()?;
  file.persist_noclobber(path).map_err(|e| e.error)?;
  Ok(())
}

fn keypair(kid: String, private: &Path, public: &Path, format: KeyFormat) -> Result<()> {
  identifier(&kid)?;
  if private == public || private.try_exists()? || public.try_exists()? {
    return Err("key output paths must be distinct and must not already exist".into());
  }
  let key = SigningKey::from_bytes(&random::<32>()?);
  let mut jwk = Jwk {
    kty: "OKP".into(),
    crv: "Ed25519".into(),
    alg: "EdDSA".into(),
    usage: "sig".into(),
    kid,
    x: B64.encode(key.verifying_key().as_bytes()),
    d: None,
  };
  let (private_bytes, public_bytes) = match format {
    KeyFormat::Jwk => {
      let public_bytes = serde_json::to_vec_pretty(&json!({"keys": [&jwk]}))?;
      jwk.d = Some(B64.encode(key.to_bytes()));
      (serde_json::to_vec_pretty(&jwk)?, public_bytes)
    }
    KeyFormat::Pem => (
      key.to_pkcs8_pem(Default::default())?.as_bytes().to_vec(),
      key
        .verifying_key()
        .to_public_key_pem(Default::default())?
        .into_bytes(),
    ),
  };
  write_new(private, &private_bytes)?;
  // Preserve the private key if exporting the public half fails.
  write_new(public, &public_bytes)?;
  Ok(())
}

fn read_key(path: &Path) -> Result<Jwk> {
  let bytes = fs::read(path)?;
  if bytes.len() > 16 * 1024 {
    return Err("private JWK is too large".into());
  }
  let jwk: Jwk = serde_json::from_slice(&bytes).map_err(|_| "invalid private JWK JSON")?;
  identifier(&jwk.kid)?;
  if jwk.kty != "OKP" || jwk.crv != "Ed25519" || jwk.alg != "EdDSA" || jwk.usage != "sig" {
    return Err("expected an Ed25519 signing JWK".into());
  }
  Ok(jwk)
}

fn signing_key(jwk: &Jwk) -> Result<SigningKey> {
  let bytes: [u8; 32] = B64
    .decode(jwk.d.as_ref().ok_or("private JWK is missing d")?)
    .map_err(|_| "invalid private key encoding")?
    .try_into()
    .map_err(|_| "invalid private key length")?;
  let key = SigningKey::from_bytes(&bytes);
  if B64.encode(key.verifying_key().as_bytes()) != jwk.x {
    return Err("private and public key disagree".into());
  }
  Ok(key)
}

fn claims(mut body: Value, days: u64, now: u64) -> Result<Value> {
  let object = body.as_object_mut().ok_or("claims must be a JSON object")?;
  if ["iat", "exp", "jti"]
    .iter()
    .any(|key| object.contains_key(*key))
  {
    return Err("iat, exp and jti are generated; omit them from the claims file".into());
  }
  if days == 0 {
    return Err("validity days must be positive".into());
  }
  let expires = days
    .checked_mul(86400)
    .and_then(|duration| now.checked_add(duration))
    .filter(|n| *n <= MAX_SAFE_INTEGER)
    .ok_or("validity exceeds supported timestamp range")?;
  object.insert("iat".into(), now.into());
  object.insert("exp".into(), expires.into());
  object.insert("jti".into(), B64.encode(random::<16>()?).into());
  Ok(body)
}

fn load_signer(path: &Path, kid: Option<String>) -> Result<(SigningKey, String)> {
  let text = fs::read_to_string(path)?;
  if text.trim_start().starts_with('{') {
    let jwk = read_key(path)?;
    if kid.as_ref().is_some_and(|id| id != &jwk.kid) {
      return Err("--kid does not match private JWK".into());
    }
    Ok((signing_key(&jwk)?, jwk.kid))
  } else {
    let kid = kid.ok_or("PEM signing keys require --kid")?;
    identifier(&kid)?;
    let key =
      SigningKey::from_pkcs8_pem(&text).map_err(|_| "invalid Ed25519 PKCS#8 private PEM")?;
    Ok((key, kid))
  }
}

fn sign(key: &SigningKey, kid: &str, body: &Value) -> Result<String> {
  let header = json!({"alg":"EdDSA", "typ":"JWT", "kid":kid});
  let input = format!(
    "{}.{}",
    B64.encode(serde_json::to_vec(&header)?),
    B64.encode(serde_json::to_vec(body)?)
  );
  Ok(format!(
    "{input}.{}",
    B64.encode(key.sign(input.as_bytes()).to_bytes())
  ))
}

fn run() -> Result<()> {
  match Args::parse().command {
    Command::Keypair {
      kid,
      format,
      private_key,
      public_key,
    } => keypair(kid, &private_key, &public_key, format),
    Command::Token {
      key,
      claims: input,
      kid,
      days,
      output,
    } => {
      let (key, kid) = load_signer(&key, kid)?;
      let bytes = fs::read(input)?;
      if bytes.len() > 16 * 1024 {
        return Err("claims file is too large".into());
      }
      let body: Value = serde_json::from_slice(&bytes).map_err(|_| "invalid claims JSON")?;
      let now = SystemTime::now().duration_since(UNIX_EPOCH)?.as_secs();
      let body = claims(body, days, now)?;
      let token = sign(&key, &kid, &body)?;
      write_new(&output, format!("{token}\n").as_bytes())
    }
  }
}

fn main() {
  if let Err(error) = run() {
    eprintln!("q2q-keygen: {error}");
    std::process::exit(1);
  }
}

#[cfg(test)]
mod tests {
  use super::*;
  use ed25519_dalek::{Signature, Verifier};

  #[test]
  fn formats_roundtrip_and_jwt_detects_tampering() {
    let dir = tempfile::tempdir().unwrap();
    for (i, format) in [KeyFormat::Jwk, KeyFormat::Pem].into_iter().enumerate() {
      let private = dir.path().join(format!("private-{i}"));
      let public = dir.path().join(format!("public-{i}"));
      keypair("test-key".into(), &private, &public, format).unwrap();
      let (key, kid) = load_signer(&private, Some("test-key".into())).unwrap();
      let exported = fs::read_to_string(&public).unwrap();
      assert!(!exported.contains("PRIVATE KEY"));
      if matches!(format, KeyFormat::Jwk) {
        let jwks: Value = serde_json::from_str(&exported).unwrap();
        assert!(jwks["keys"][0].get("d").is_none());
      }
      let body = claims(
        json!({"sub":"arbitrary-service", "custom":{"role":"reader"}}),
        90,
        1000,
      )
      .unwrap();
      assert_eq!(body["exp"], 1000 + 90 * 86400);
      assert_eq!(body["custom"]["role"], "reader");
      assert!(body.get("scope").is_none());
      let token = sign(&key, &kid, &body).unwrap();
      let (input, signature) = token.rsplit_once('.').unwrap();
      let signature = Signature::from_slice(&B64.decode(signature).unwrap()).unwrap();
      key
        .verifying_key()
        .verify(input.as_bytes(), &signature)
        .unwrap();
      assert!(
        key
          .verifying_key()
          .verify(format!("{input}x").as_bytes(), &signature)
          .is_err()
      );
      assert!(keypair("test-key".into(), &private, &public, format).is_err());
      #[cfg(unix)]
      {
        use std::os::unix::fs::PermissionsExt;
        assert_eq!(
          fs::metadata(&private).unwrap().permissions().mode() & 0o777,
          0o600
        );
      }
    }
  }

  #[test]
  fn rejects_invalid_claims_and_unsafe_validity() {
    assert!(claims(json!([]), 90, 1000).is_err());
    assert!(claims(json!({"exp":2000}), 90, 1000).is_err());
    assert!(claims(json!({}), 0, 1000).is_err());
    assert!(claims(json!({}), u64::MAX, 1000).is_err());
    assert!(identifier("../key").is_err());
  }
}
