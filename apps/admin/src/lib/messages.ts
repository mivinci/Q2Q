export type Locale = keyof typeof messages;
export type MessageKey = keyof typeof messages.en;
export function resolveLocale(preference: string | undefined, language: string): Locale {
 if (preference === 'en' || preference === 'zh-CN') return preference;
 const choices = language.split(',').map((part) => {
  const [tag, ...params] = part.trim().split(';');
  const q = params.find(value => value.trim().startsWith('q='));
  return { tag: tag.toLowerCase(), q: q ? Number(q.trim().slice(2)) : 1 };
 }).filter(item => Number.isFinite(item.q) && item.q > 0 && item.q <= 1).sort((a,b) => b.q-a.q);
 for (const {tag} of choices) { if (tag === 'zh' || tag.startsWith('zh-')) return 'zh-CN'; if (tag === 'en' || tag.startsWith('en-')) return 'en'; }
 return 'en';
}
